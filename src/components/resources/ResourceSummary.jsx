import { useState } from 'react';
import getNavigatorPrintTheme from '@/components/brand/getNavigatorPrintTheme';
import { base44 } from '@/api/base44Client';
import { Button } from '@/components/ui/button';
import { Sparkles, Printer, ChevronDown, ChevronUp, Loader2 } from 'lucide-react';

export default function ResourceSummary({ resource }) {
  const [summary, setSummary] = useState(null);
  const [loading, setLoading] = useState(false);
  const [expanded, setExpanded] = useState(false);

  const handleGenerate = async () => {
    setLoading(true);
    try {
      const resourceText = `Resource Name: ${resource.name}
Organization: ${resource.org}
Description: ${resource.description}
Type: ${resource.type}
Topics: ${(resource.topics || []).join(', ')}`;
      const result = (await base44.functions.invoke('aiGateway', { operation: 'summarize_resource', data: { resourceText } })).data.result;
      setSummary(result);
      setExpanded(true);
      base44.analytics.track({
        eventName: 'resource_summary_generated',
        properties: {
          resource_id: resource.id,
          resource_name: resource.name,
          resource_category: resource.type,
        },
      });
    } finally {
      setLoading(false);
    }
  };

  const handlePrint = () => {
    const printWindow = window.open('', '_blank');
    printWindow.document.write(`
      <html>
        <head>
          <title>Resource Summary – ${resource.name}</title>
          <style>${getNavigatorPrintTheme()}</style>
        </head>
        <body>
          <h1>${resource.name}</h1>
          <div class="meta">${resource.org} &nbsp;·&nbsp; ${resource.type}</div>
          <div class="summary">${summary}</div>
          <div class="footer">
            Source: <a href="${resource.url}" target="_blank">${resource.url}</a><br/>
            Generated by Back to Life, Back to Work Navigator · ${new Date().toLocaleDateString()}
          </div>
        </body>
      </html>
    `);
    printWindow.document.close();
    printWindow.print();
    base44.analytics.track({
      eventName: 'resource_summary_printed',
      properties: { resource_id: resource.id, resource_name: resource.name },
    });
  };

  return (
    <div className="mt-2">
      {!summary ? (
        <Button variant="outline" size="sm" onClick={handleGenerate} disabled={loading}>
          {loading ? <Loader2 className="h-3 w-3 mr-1.5 animate-spin" /> : <Sparkles className="h-3 w-3 mr-1.5" />}
          {loading ? 'Generating summary…' : 'AI Summary'}
        </Button>
      ) : (
        <div className="nv-card nv-card--muted p-3 space-y-2">
          <div className="flex items-center justify-between gap-2 flex-wrap">
            <span className="text-xs font-semibold text-brand-primary flex items-center gap-1"><Sparkles className="h-3 w-3" /> AI Summary</span>
            <div className="flex gap-1.5">
              <button onClick={handlePrint} className="nv-btn nv-btn--text nv-btn--sm"><Printer className="h-3 w-3" /> Print PDF</button>
              <button onClick={() => setExpanded(!expanded)} aria-label={expanded ? 'Collapse summary' : 'Expand summary'} aria-expanded={expanded} className="nv-btn nv-btn--text nv-btn--icon">
                {expanded ? <ChevronUp className="h-3 w-3" /> : <ChevronDown className="h-3 w-3" />}
              </button>
            </div>
          </div>
          {expanded && <p className="text-xs text-brand-text">{summary}</p>}
        </div>
      )}
    </div>
  );
}